"use client";
import { useState } from "react";
import rag from "@/public/data/rag_saved.json";
import { Caveat, PageHeader, Panel } from "@/components/ui";
import { pick, useAudience } from "@/lib/audience";
import { REPO_URL, STREAMLIT_URL } from "@/lib/config";
import LiveAsk from "@/components/LiveAsk";

type Answer = (typeof rag.answers)[number];
type Passage = Answer["passages"][number];

function Quote({ p }: { p: Passage }) {
  const where = p.doc_title + (p.section && p.section !== p.doc_title ? `, ${p.section}` : "");
  return (
    <div className="mt-3">
      <div className="text-sm">
        <strong>[{p.passage_id}]</strong>{" "}
        <span className={`rounded px-1.5 py-0.5 text-xs ${p.source_type === "data_card" ? "bg-[#4594ee]/20 text-cool-ink" : "bg-panel-2 text-muted"}`}>
          {p.source_label}
        </span>{" "}
        {where} - <a href={p.source_url}>open source</a>
      </div>
      <blockquote className="mt-1 border-l-2 border-line pl-3 text-sm whitespace-pre-line text-muted">{p.text}</blockquote>
    </div>
  );
}

function Card({ a, open }: { a: Answer; open: boolean }) {
  const cited = a.passages.filter((p) => p.cited && p.field !== "publication title");
  const pubs = a.passages.filter((p) => p.field === "publication title");
  const other = a.passages.filter((p) => !p.cited && p.field !== "publication title");
  const weak = new Map(a.support.filter((s) => s.weak).map((s) => [s.line.trim(), s]));
  return (
    <details open={open} className="rounded-lg border border-line bg-panel">
      <summary className="px-4 py-3 font-semibold">{a.question}</summary>
      <div className="min-w-0 px-4 pb-4">
        <p className="text-xs text-muted">
          AI-generated (Gemini, {a.model}) on {a.saved_utc} UTC, checked: every claim cites a retrieved passage.
          Saved in the repository, not a live call.
        </p>
        <ul className="mt-3 space-y-1">
          {a.text.split("\n").filter((l) => l.trim()).map((l) => {
            const w = weak.get(l.trim());
            return (
              <li key={l} className="ml-5 list-disc">
                {l.replace(/^\s*[-*]\s*/, "")}
                {w && <span className="ml-2 rounded bg-warn-bg px-1.5 py-0.5 text-xs text-warn">
                  weakly supported: {Math.round(w.share * 100)}% of its words are in the cited text</span>}
              </li>
            );
          })}
        </ul>
        {cited.length > 0 && <h3 className="mt-4 text-sm font-semibold">Cited passages, word for word</h3>}
        {cited.map((p) => <Quote key={p.passage_id} p={p} />)}
        {pubs.length > 0 && (
          <>
            <h3 className="mt-4 text-sm font-semibold">Related publications</h3>
            <ul className="mt-1 ml-5 list-disc text-sm">
              {pubs.map((p) => (
                <li key={p.passage_id}>{p.text} - {p.doc_title}, <a href={p.source_url}>open PSI page</a>{" "}
                  <strong>[{p.passage_id}]</strong>{p.cited ? " (cited above)" : ""}</li>
              ))}
            </ul>
          </>
        )}
        {other.length > 0 && (
          <details className="mt-3">
            <summary className="text-sm text-muted">Other retrieved passages, not cited ({other.length})</summary>
            {other.map((p) => <Quote key={p.passage_id} p={p} />)}
          </details>
        )}
      </div>
    </details>
  );
}

export default function AskPage() {
  const { audience } = useAudience();
  const [all, setAll] = useState(false);
  const counts = rag.by_source_type as Record<string, number>;
  const labels = rag.source_labels as Record<string, string>;
  const live = STREAMLIT_URL || REPO_URL;
  return (
    <>
      <PageHeader title="Ask NASA Records"
        purpose={pick(audience, {
          researcher: "Answers grounded in retrieved passages of NASA text, each claim cited and checked against the retrieval.",
          engineer: "Answers that cite NASA's own text, passage by passage.",
          plain: "Questions about spacecraft fires, answered only from NASA's own words, with the words shown.",
        })} />

      <LiveAsk />
      <p className="mt-2 text-xs text-muted">
        The same search and checks also run in the <a href={live}>Streamlit app</a>. Below: {rag.answers.length} saved,
        checked answers that need no live call.
      </p>
      <Caveat>
        Answers are generated by an AI model from the NASA passages retrieved for the question, then checked in code: every
        claim must cite one of those passages, or the answer is rejected. A bullet whose words are mostly absent from its
        cited passages (below {Math.round(rag.support_threshold * 100)}%) is flagged as weakly supported. The check counts
        words, not meaning, so read the passages. Saved answers below were checked the same way.
      </Caveat>

      <div className="mb-2 flex justify-end">
        <button onClick={() => setAll(!all)} className="rounded-md border border-line px-3 py-1.5 text-sm hover:bg-panel-2">
          {all ? "Collapse all" : "Expand all"}
        </button>
      </div>
      <div className="space-y-3" key={`${audience}-${all}`}>
        {rag.answers.map((a, k) => <Card key={a.question} a={a} open={all || k === 0} />)}
      </div>

      <Panel title="How this works, and its limits" open={audience === "researcher"} key={`how-${audience}`}>
        <ul className="ml-5 list-disc space-y-1 text-sm">
          <li>The corpus is {rag.corpus_passages} passages copied word for word:{" "}
            {Object.entries(counts).filter(([t]) => t !== "data_card").map(([t, n]) => `${n} from ${labels[t]}s`).join("; ")};
            plus {counts.data_card} short passages <strong>computed from NASA tables</strong> by the team&apos;s code, each
            naming its source file.</li>
          <li>Only NASA-authored or NASA-published text is used. Where NASA&apos;s report server does not mark an abstract as
            free for public use, only its title and link are kept.</li>
          <li>For each question the 6 closest passages are retrieved by word matching (TF-IDF), with a limit per kind of
            source. No AI is involved in the search. On 30 check questions it found the right source for 28.</li>
          <li>The AI sees only those passages and must cite one for every claim. If the passages do not answer the
            question, it must say so.</li>
          <li>The PSI records describe what each investigation set out to do; findings come mostly from the NASA pages, the
            Researcher&apos;s Guide and the report abstracts. For numbers, use the Suppression Lab and Unified Data.</li>
        </ul>
      </Panel>
    </>
  );
}
